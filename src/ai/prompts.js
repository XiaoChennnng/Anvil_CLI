/**
 * 获取系统提示词
 * @param {Object} [options]
 * @param {boolean} [options.planMode] - 是否启用 Plan Mode
 * @returns {string}
 */
function getSystemPrompt(options = {}) {
  let prompt = SYSTEM_PROMPT;
  if (options.planMode) {
    prompt += '\n\n' + PLAN_MODE_PROMPT;
  }
  return prompt;
}

